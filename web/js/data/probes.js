/**
 * 探测器总表
 *
 *  位置口径：
 *   · mode='orbit'        正在环绕某个天体 → 按真实半长轴/周期绘制轨道并实时定位
 *   · mode='landed'       已着陆/坠毁在某个天体 → 贴在母天体表面的着陆点
 *   · mode='heliocentric' 在日心轨道上飞行 → 按真实日心距离与方向定位，并绘制轨迹
 *   · mode='ended'        任务已结束 → 归到目标天体下，标注状态
 *
 *  helio.au / lonDeg / latDeg 为参考历元（2026-09-09）的日心黄道 J2000 球坐标，
 *  由官方公布的日心距离与方向换算；speedAuPerYear 为径向速度。
 *
 *  2026-10-11 新增两列：
 *   · model：三维构型预设（键 = `objects/spacecraft.js` 的 PRESETS，唯一真源在那边）；
 *   · instruments：**科学载荷清单**（真实仪器，中文名 + 英文缩写 + 一句说明），
 *     由详情面板「科学载荷」节展示。仪器清单的口径：主要在役/主要出成果的仪器，
 *     不是全集——全集上百条会把面板拖垮，代表性优先。
 */

