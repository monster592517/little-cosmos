/**
 * 把控制点转成 380–780 nm / 5 nm 的等间隔数组（81 点）。
 * 端点外做**常数延拓**（不外推斜率）—— 外推会凭空造出颜色。
 * @param {Array<[number,number]>} points
 * @returns {Float64Array} 长度 81
 */
export function pointsToGrid(points) {
  const n = Math.round((SPEC_LAMBDA_MAX - SPEC_LAMBDA_MIN) / SPEC_LAMBDA_STEP) + 1;
  const out = new Float64Array(n);
  if (!points || points.length === 0) return out;
  const first = points[0];
  const last = points[points.length - 1];
  for (let i = 0; i < n; i++) {
    const lam = SPEC_LAMBDA_MIN + i * SPEC_LAMBDA_STEP;
    if (lam <= first[0]) { out[i] = first[1]; continue; }
    if (lam >= last[0]) { out[i] = last[1]; continue; }
    let j = 0;
    while (j < points.length - 1 && points[j + 1][0] < lam) j++;
    const [l0, v0] = points[j];
    const [l1, v1] = points[j + 1];
    const t = (lam - l0) / (l1 - l0);
    out[i] = v0 + (v1 - v0) * t;
  }
  return out;
}

/**
 * 把一条谱缩放到指定的视觉几何反照率。
 *
 * 做法：先按 CIE 算出曲线当前的「等能白加权平均反射率」（即 Y），
 * 再整体乘 geoAlbedo/Y。这样**只改亮度、完全不动色相**。
 *
 * ⚠️ 为什么需要这一步：不同文献给反照率的**口径不同**（Bond vs 几何，
 *    圆面 vs 局部，不同相位角），直接把曲线喂进颜色计算会得到互相
 *    矛盾的亮度。统一锚到几何反照率后，"形状来自观测、亮度来自权威表"
 *    两件事各归其位，且可审计。
 *
 * @param {Array<[number,number]>|ArrayLike<number>} spectrum 控制点或 81 点栅格
 * @param {number} geoAlbedo 目标视觉几何反照率
 * @returns {Float64Array} 缩放后的 81 点栅格
 */
export function normalizeToGeo(spectrum, geoAlbedo) {
  const grid = Array.isArray(spectrum) && Array.isArray(spectrum[0])
    ? pointsToGrid(spectrum)
    : spectrum;
  if (!(geoAlbedo > 0)) return grid;
  // 等能白下的加权平均反射率：直接复用 ȳ 权重
  let num = 0, den = 0;
  for (let i = 0; i < grid.length; i++) {
    // 用 CIE ȳ 的近似（人眼亮度响应）做权重，不必精确 —— 只为缩放
    const lam = SPEC_LAMBDA_MIN + i * SPEC_LAMBDA_STEP;
    const w = luminanceWeight(lam);
    num += grid[i] * w;
    den += w;
  }
  const y = den > 0 ? num / den : 1;
  if (!(y > 1e-9)) return grid;
  const k = geoAlbedo / y;
  const out = new Float64Array(grid.length);
  for (let i = 0; i < grid.length; i++) out[i] = grid[i] * k;
  return out;
}

/**
 * CIE 1931 ȳ(λ) 的分段线性近似，仅在 5 nm 栅格上取点。
 * 只用于 photosynthesis 式的加权平均（颜色计算走 cie.js 的正式表）。
 */
function luminanceWeight(lam) {
  // 简化高斯式拟合，误差 < 3%，足够做加权缩放
  const t = (lam - 555) / 95;
  return Math.exp(-0.5 * t * t);
}

/**
 * 取某天体的「可直接用于渲染/着色」的光谱：已归一化到几何反照率。
 * @param {string} id
 * @returns {Float64Array|null}
 */
export function renderSpectrum(id) {
  const e = SPECTRA[id];
  if (!e) return null;
  return normalizeToGeo(e.points, e.geoAlbedo);
}

export default SPECTRA;
