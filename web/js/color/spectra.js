/**
 * 全天体真彩光谱库 —— 「真实的样子」的数据来源
 *
 * ══════════════════════════════════════════════════════════════
 * 这个文件解决什么问题
 * ══════════════════════════════════════════════════════════════
 * 用户原话：「很多照片都是经过特殊处理方便研究他们的大气以及其他结构的，
 * 都不是真实的样子，真实的样子需要你自己仔细去全网找或者甚至扒公开的
 * 原始数据自己算」。
 *
 * 所以本文件里**每一个光谱都必须带 `src` 出处**。规则：
 *
 *   · 有公开观测数据支撑的 → 写实测值，`src` 指到论文/数据集，
 *     并标注 `conf`（置信度）与 `note`（口径说明，比如相位角）。
 *   · 只有颜色描述、没有光谱的 → 不硬编光谱，写 `src: null` 并给
 *     `hintHex` 让调用方走「程序化生成」分支。见 spectra.js 尾部说明。
 *   · 拿不准的一律不写。宁可标 null，也不许凭印象填 —— 见 坑与雷点.md 坑 33。
 *
 * ══════════════════════════════════════════════════════════════
 * 关键概念：反射率谱 ≠ 颜色
 * ══════════════════════════════════════════════════════════════
 * 一个物体的颜色 = 它反射的光谱 × 照射它的光源光谱，再经人眼积分。
 * 本库存的都是**反射率（反照率）**，是无量纲比值（0..1）。
 * 真正算颜色要交给 cie.js 的 spectrumToHex()，默认用等能白照射。
 *
 * ⚠️ 不要直接把这些反射率当 sRGB 用。反射率是线性的、跨波长的，
 *    颜色是积分结果。中间必须过 CIE 1931。
 *
 * ══════════════════════════════════════════════════════════════
 * 已知的系统性坑（写代码前先读）
 * ══════════════════════════════════════════════════════════════
 * 1. **反射率谱平 ≠ 白色天体**。等能白照射下，平谱积分出来的就是纯白。
 *    所以任何「我觉得这里应该有点颜色」的直觉都不能进数据。金星云顶
 *    在 500 nm 以上反射率高达 0.9，但 400 nm 以下掉到 0.5 上下 —— 正是
 *    这个蓝端缺口让它呈淡黄白，而不是纯白。数值差一点点，色相就差很多。
 * 2. **相位角会改颜色**。同一个天体，不同相位角下红/蓝比可以差 33%
 *    （火星土壤实测）。本库统一采用**低相位角（≤5°）几何反照率**，
 *    即「从地球看、太阳几乎在背后」的条件，对应人眼看到的圆面。
 * 3. **甲浣吸收带要落在采样点内**。天王星/海王星的青色来自 CH4 在
 *    620–730 nm 的吸收。5 nm 采样能覆盖，但若只用 3 个点插值就会漏掉。
 */

/* ==============================================================
   0. 谱的表示方式 + 一个必须写死的口径
   ==============================================================
   用 `points` 表示非等间隔控制点（节省体积、只记关键拐点），
   cie.js 的 spectrumFromPoints() 会线性插值到 5 nm 栅格。
   等间隔的用 `values` + `lambda0` + `step`，更省。
   两者都支持。每个条目统一结构见下方 `ENTRIES`。

   ──────────────────────────────────────────────────────────────
   ★ 口径约定：本库所有曲线一律是「视觉几何反照率谱」
   ──────────────────────────────────────────────────────────────
   反照率有好几种，混用会出错。为避免这一点，本库规定：

     · 一律使用 **视觉几何反照率（visual geometric albedo, p）**
       —— 即零相位角下、圆面亮度与同样截面的朗伯盘之比。
     · 即「从地球看、太阳几乎在正后方」的条件，对应人眼看到的圆面。
     · **不使用 Bond/球面反照率**。后者是把所有相位角积分后的能量比
       （A = p·q，q 是相位积分），它比几何反照率小或大（金星 q=1.35），
       混进来会让颜色计算系统性偏亮或偏暗。

   ⚠️ 为什么必须写死这条：我在做金星时踩过一次 —— 拿 Limaye 2021 的
      「Bond 反照率按波长表」（600nm 处 0.95）当反射率曲线用，算出来
      Y=0.88，而 Mallama 2017 给的几何反照率是 0.689。两者都对，
      但**不是同一个量**。混用会让所有天体的"亮度"这一维失真。

   基准值（Mallama, Krobusek & Pavlov 2017, Icarus 282, 19 —— 行星反照率
   的权威汇总；以及 Mallama 2006 Icarus 182,10 对金星的专测）：
     水星  Bond 0.088  几何 0.142
     金星  Bond 0.76   几何 0.689   （相位积分 1.35）
     月球  Bond 0.11   几何 0.12
     火星  Bond 0.25   几何 0.17
     木星  Bond 0.503  几何 0.538
     土星  Bond 0.342  几何 0.499
     天王星 Bond 0.300  几何 0.488
     海王星 Bond 0.290  几何 0.442
     土卫二 Bond 0.81   几何 1.375
     冥王星 Bond 0.41   几何 0.51
   → 每个条目都带 `geoAlbedo` 字段记录这个基准，并可用
     `normalizeToGeo()` 把曲线缩放到与之一致，保证「谱的形状」和
     「公开的亮度数值」不会互相打架。
   ============================================================== */

