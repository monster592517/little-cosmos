/**
 * 系外行星的**示意色**：平衡温度 → 颜色。
 *
 * ⚠️ 先读这段再改 —— 这是「示意色」，不是观测结论。
 *
 *   本模块属于真彩还原链（见 `cie.js` 文件头的口径）的**第三档**：
 *     高：实测光谱 / 反照率谱 —— 太阳系 50 个天体，走 `spectra.js` + `cie.js`
 *     中：色指数反推        —— 不规则卫星 + 部分恒星，走 `indices-to-spectrum.js`
 *     低：属性生成·**示意** —— 本模块。系外行星拿不到反照率谱，
 *                              连半径都常常只有下限，**不可能**算真彩。
 *
 *   所以这里只用**一条有物理依据的粗判据**：平衡温度。
 *   它决定行星会不会自己发热发光、以及被照亮到什么程度：
 *     · >1000 K  炽热 —— 偏红（热辐射开始主导，类似 M 型矮星照明下的热木星）
 *     · 700–1000 K 红橙
 *     · 400–700 K  橙色
 *     · 250–400 K  黄白（宜居带附近）
 *     · 150–250 K  淡蓝
 *     · <150 K    冰蓝白（冷行星）
 *   拿不到温度的（大量只有质量的径向速度行星）退回灰白 `#b9c4d4`。
 *
 * ⚠️ 这个映射**必须只有这一份**。曾经它在 `objects/exo-planets.js` 里，
 *   而数据集要建天体对象又需要它 —— 如果那时各自抄一份，
 *   「渲染出来的颜色」和「目录里的色块」就会慢慢漂开，
 *   而且**没人会发现**（两个地方各自都"看起来对"）。
 *   所以它住在 color/ 层：谁要这个色，都来这里拿。
 */

/** 灰白：拿不到平衡温度时的兜底（不要改成某个"好看"的颜色） */
export const NO_TEMP_COLOR = '#b9c4d4';

/**
 * 平衡温度（K）→ 示意色。
 *
 * 用分段线性插值而不是连续函数：这几档的**分界是有物理含义的**
 * （宜居带、热辐射主导），插值只是把档与档之间连起来，别把它当光谱模型。
 *
 * ⚠️ **返回 `#rrggbb`**（历史上返回 `rgb(r,g,b)`）。改的理由与其他颜色生产者一致：
 *   项目里 `color` 字段的口径是 `#rrggbb`（321 个手写天体全是），
 *   而 `proc/textures.js` 的 `hexToRgb()` 只能解析 hex ——
 *   喂 `rgb(...)` 它会 `parseInt('rg',16)` 得到 NaN，安静地画出黑贴图。
 *
 * @param {number} tempK 平衡温度，单位 K
 * @returns {string} `#rrggbb`
 */
export function tempToColor(tempK) {
  const hex = (c) => '#' + c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
  if (!Number.isFinite(tempK)) return NO_TEMP_COLOR;
  const stops = [
    [120, [200, 224, 255]],
    [200, [215, 234, 255]],
    [280, [246, 244, 236]],
    [420, [255, 214, 158]],
    [700, [255, 168, 110]],
    [1100, [255, 122, 86]],
    [2000, [255, 92, 70]],
  ];
  if (tempK <= stops[0][0]) return hex(stops[0][1]);
  for (let i = 0; i < stops.length - 1; i++) {
    const [t0, c0] = stops[i], [t1, c1] = stops[i + 1];
    if (tempK >= t0 && tempK <= t1) {
      const f = (tempK - t0) / (t1 - t0);
      return hex(c0.map((v, k) => v + (c1[k] - v) * f));
    }
  }
  return hex(stops[stops.length - 1][1]);
}

/** 这一档颜色在界面上的可信度标签，用来提示读者「别当观测结论」 */
export const EXO_COLOR_TRUST = '示意色（按平衡温度生成，非观测真彩）';
