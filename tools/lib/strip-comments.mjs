/**
 * 剥掉 JS 注释 —— **全项目唯一一份**。
 *
 * ⚠️ 判「源码里有没有这句话」必须**先剔注释**：本项目在这上面误判过
 *    （把注释里的示例当成活代码、把注释里的字段名当成真实用法）。
 * ⚠️ 反过来也踩过：**找字面量时剔注释，判豁免时看原始行** ——
 *    行内自证（「这个空实现是有意的」）恰恰**写在注释里**，剔掉就看不见了。
 *    所以调用方要按用途各取所需，别把这两件事混在一次扫描里。
 *
 * 为什么要抽成模块：`check-localgroup.mjs` 与 `check-scale-rings.mjs` 都要用它，
 * 而同一条不变量两份实现**必漏一份**（这是本项目反复吃过的亏）。
 */
export function stripComments(src) {
  return String(src).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
